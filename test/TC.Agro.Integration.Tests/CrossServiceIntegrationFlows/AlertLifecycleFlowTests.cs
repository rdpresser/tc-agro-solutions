    private async Task<ProducerContext> CreateProducerContextAsync(CancellationToken cancellationToken)
    {
        var token = Guid.NewGuid().ToString("N")[..8];
        var password = "Producer@123";

        var createCmd = new CreateUserCommand(
            Name: $"Producer {token}",
            Email: $"producer.alerts.{token}@tcagro.test",
            Username: $"produceralerts{token}",
            Password: password,
            Role: "Producer");

        using var createResp = await Fixture.IdentityClient
            .PostAsJsonAsync("/auth/register", createCmd, cancellationToken);

        createResp.StatusCode.ShouldBe(HttpStatusCode.Created);

        var created = await createResp.Content
            .ReadFromJsonAsync<CreateUserResponse>(cancellationToken: cancellationToken);

        created.ShouldNotBeNull();

        using var loginResp = await Fixture.IdentityClient
            .PostAsJsonAsync("/auth/login", new LoginUserCommand(createCmd.Email, password), cancellationToken);

        loginResp.StatusCode.ShouldBe(HttpStatusCode.OK);

        var login = await loginResp.Content
            .ReadFromJsonAsync<LoginUserResponse>(cancellationToken: cancellationToken);

        login!.JwtToken.ShouldNotBeNullOrWhiteSpace();

        await Fixture.WaitForFarmOwnerSnapshotAsync(created!.Id, TimeSpan.FromSeconds(45), cancellationToken: cancellationToken);
        await Fixture.WaitForAnalyticsOwnerSnapshotAsync(created.Id, TimeSpan.FromSeconds(45), cancellationToken: cancellationToken);

        return new ProducerContext(created.Id, login.JwtToken, token);
    }

    private async Task<(Guid PropertyId, Guid PlotId, Guid SensorId)> SetupFarmHierarchyAsync(
        ProducerContext producer,
        CancellationToken cancellationToken)
    {
        var propCmd = new CreatePropertyCommand(
            Name: $"Alert Test Property {producer.Token}",
            Address: "Alert Test Road, km 01",
            City: "Ribeirao Preto",
            State: "SP",
            Country: "Brazil",
            AreaHectares: 50.0,
            Latitude: -21.1767,
            Longitude: -47.8208);

        using var propResp = await SendAuthorizedJsonAsync(
            Fixture.FarmClient, HttpMethod.Post, "/api/properties",
            propCmd, producer.JwtToken, cancellationToken);

        propResp.StatusCode.ShouldBe(HttpStatusCode.Created);
        var property = await propResp.Content
            .ReadFromJsonAsync<CreatePropertyResponse>(cancellationToken: cancellationToken);
        property.ShouldNotBeNull();

        var cropTypeCatalogId = await Fixture.EnsureFarmSystemCropCatalogAsync("Corn", cancellationToken);

        var plotCmd = new CreatePlotCommand(
            PropertyId: property!.Id,
            Name: $"Alert Plot {producer.Token}",
            CropType: "Corn",
            AreaHectares: 20.0,
            Latitude: -21.1775,
            Longitude: -47.8103,
            BoundaryGeoJson: "{\"type\":\"Polygon\",\"coordinates\":[[[-47.811,-21.178],[-47.809,-21.178],[-47.809,-21.176],[-47.811,-21.176],[-47.811,-21.178]]]}",
            PlantingDate: DateTimeOffset.UtcNow.AddDays(-10),
            ExpectedHarvestDate: DateTimeOffset.UtcNow.AddDays(90),
            IrrigationType: "Drip Irrigation",
            AdditionalNotes: "Alert test plot",
            CropTypeCatalogId: cropTypeCatalogId);

        using var plotResp = await SendAuthorizedJsonAsync(
            Fixture.FarmClient, HttpMethod.Post, "/api/plots",
            plotCmd, producer.JwtToken, cancellationToken);

        plotResp.StatusCode.ShouldBe(HttpStatusCode.Created);
        var plot = await plotResp.Content
            .ReadFromJsonAsync<CreatePlotResponse>(cancellationToken: cancellationToken);
        plot.ShouldNotBeNull();

        var sensorCmd = new CreateSensorCommand(
            PlotId: plot!.Id,
            Type: "Temperature",
            Label: $"Alert Sensor {producer.Token}",
            OwnerId: producer.UserId);

        using var sensorResp = await SendAuthorizedJsonAsync(
            Fixture.FarmClient, HttpMethod.Post, "/api/sensors",
            sensorCmd, producer.JwtToken, cancellationToken);

        sensorResp.StatusCode.ShouldBe(HttpStatusCode.Created);
        var sensor = await sensorResp.Content
            .ReadFromJsonAsync<CreateSensorResponse>(cancellationToken: cancellationToken);
        sensor.ShouldNotBeNull();

        // Wait for sensor snapshot to be propagated to analytics
        await Fixture.WaitForAnalyticsSensorSnapshotAsync(
            sensor!.Id, TimeSpan.FromSeconds(45), cancellationToken: cancellationToken);

        return (property.Id, plot.Id, sensor.Id);
    }

    private async Task IngestCriticalTemperatureReadingAsync(
        ProducerContext producer,
        Guid sensorId,
        double temperature,
        CancellationToken cancellationToken)
    {
        var command = new CreateReadingCommand(
            SensorId: sensorId,
            Timestamp: DateTime.UtcNow,
            Temperature: temperature,          // Above threshold (35°C) → triggers alert
            Humidity: 55.0,
            SoilMoisture: 40.0,
            Rainfall: null,
            BatteryLevel: 85.0);

        using var response = await SendAuthorizedJsonAsync(
            Fixture.SensorIngestClient, HttpMethod.Post, "/api/readings",
            command, producer.JwtToken, cancellationToken);

        response.StatusCode.ShouldBe(HttpStatusCode.OK,
            await response.Content.ReadAsStringAsync(cancellationToken));
    }

    private static Task<HttpResponseMessage> SendAuthorizedJsonAsync<TPayload>(
        HttpClient client,
        HttpMethod method,
        string route,
        TPayload payload,
        string jwtToken,
        CancellationToken cancellationToken)
    {
        var request = new HttpRequestMessage(method, route)
        {
            Content = JsonContent.Create(payload)
        };
        request.Headers.Authorization = new AuthenticationHeaderValue("Bearer", jwtToken);
        return client.SendAsync(request, cancellationToken);
    }

    private sealed record ProducerContext(Guid UserId, string JwtToken, string Token);
}
