/// <summary>
/// E2E tests for the Alert lifecycle: pending → acknowledge → resolve.
/// Verifies that analytics alerts are generated from ingested sensor readings
/// and that the acknowledge/resolve endpoints work correctly.
/// </summary>
public sealed class AlertLifecycleFlowTests : BaseIntegrationTest
{
    public AlertLifecycleFlowTests(CrossServiceIntegrationFixture fixture)
        : base(fixture)
    {
    }

    // ──────────────────────────────────────────
    // Full acknowledge lifecycle
    // ──────────────────────────────────────────

    [Fact]
    public async Task GivenCriticalReading_WhenAlertIsCreated_ThenProducerCanAcknowledgeIt()
    {
        var cancellationToken = TestContext.Current.CancellationToken;
        var producer = await CreateProducerContextAsync(cancellationToken);
        var (propertyId, plotId, sensorId) = await SetupFarmHierarchyAsync(producer, cancellationToken);

        // Ingest a reading that exceeds the temperature threshold
        await IngestCriticalTemperatureReadingAsync(
            producer, sensorId, temperature: 45, cancellationToken);

        // Wait for alert to be generated by analytics worker
        var alertRow = await Fixture.WaitForAnalyticsAlertAsync(
            sensorId,
            timeout: TimeSpan.FromSeconds(60),
            cancellationToken: cancellationToken);

        alertRow.ShouldNotBeNull("Expected at least one alert to be generated for the critical reading.");
        var alertId = alertRow!.Id;

        // Acknowledge the alert
        var acknowledgeCommand = new AcknowledgeAlertCommand(alertId);

        using var ackResponse = await SendAuthorizedJsonAsync(
            Fixture.AnalyticsClient,
            HttpMethod.Put,
            $"/api/alerts/{alertId}/acknowledge",
            acknowledgeCommand,
            producer.JwtToken,
            cancellationToken);

        ackResponse.StatusCode.ShouldBe(HttpStatusCode.OK, await ackResponse.Content.ReadAsStringAsync(cancellationToken));

        var ackResult = await ackResponse.Content
            .ReadFromJsonAsync<AcknowledgeAlertResponse>(cancellationToken: cancellationToken);

        ackResult.ShouldNotBeNull();
        ackResult!.Id.ShouldBe(alertId);
        ackResult.Status.ShouldBe("Acknowledged");
        ackResult.AcknowledgedBy.ShouldBe(producer.UserId);
    }

    // ──────────────────────────────────────────
    // Full resolve lifecycle
    // ──────────────────────────────────────────

    [Fact]
    public async Task GivenCriticalReading_WhenAlertIsCreated_ThenProducerCanResolveIt()
    {
        var cancellationToken = TestContext.Current.CancellationToken;
        var producer = await CreateProducerContextAsync(cancellationToken);
        var (_, _, sensorId) = await SetupFarmHierarchyAsync(producer, cancellationToken);

        await IngestCriticalTemperatureReadingAsync(
            producer, sensorId, temperature: 48, cancellationToken);

        var alertRow = await Fixture.WaitForAnalyticsAlertAsync(
            sensorId,
            timeout: TimeSpan.FromSeconds(60),
            cancellationToken: cancellationToken);

        alertRow.ShouldNotBeNull();
        var alertId = alertRow!.Id;

        var resolveCommand = new ResolveAlertCommand(
            AlertId: alertId,
            ResolutionNotes: "Irrigation pump was restarted. Temperature normalized.");

        using var resolveResponse = await SendAuthorizedJsonAsync(
            Fixture.AnalyticsClient,
            HttpMethod.Put,
            $"/api/alerts/{alertId}/resolve",
            resolveCommand,
            producer.JwtToken,
            cancellationToken);

        resolveResponse.StatusCode.ShouldBe(HttpStatusCode.OK,
            await resolveResponse.Content.ReadAsStringAsync(cancellationToken));

        var resolveResult = await resolveResponse.Content
            .ReadFromJsonAsync<ResolveAlertResponse>(cancellationToken: cancellationToken);

        resolveResult.ShouldNotBeNull();
        resolveResult!.Status.ShouldBe("Resolved");
        resolveResult.ResolvedBy.ShouldBe(producer.UserId);
        resolveResult.ResolutionNotes?.ShouldContain("Irrigation pump");
    }

